const crypto = require('crypto');
const { PaymentProvider, qrSvg } = require('./provider');
const phonepe = require('../../config/phonepe');
const ApiError = require('../../utils/ApiError');
const logger = require('../../utils/logger');
const { PAYMENT_STATUS } = require('../../constants/paymentStatus');

/**
 * PhonePe, against the v2 Standard Checkout API.
 *
 * Every endpoint, header, field name and status value in this file is from
 * PhonePe's own API reference, cited in docs/PHONEPE.md. None of it is guessed,
 * and where their documentation contradicts itself — the sandbox host is
 * written two ways — the base URL is configurable rather than picked silently.
 *
 * WHAT THIS PROVIDER IS AND IS NOT ALLOWED TO DECIDE. It can report what
 * PhonePe says. It cannot settle anything: `verifyPayment` returns a status and
 * the payment service decides what that means for the ride. That separation is
 * why no callback body, however well-formed, can complete a ride on its own —
 * the webhook handler re-asks PhonePe before believing it.
 *
 * REDIRECT, NOT QR. Standard Checkout hands back a `redirectUrl` the customer
 * opens; PhonePe's own page then offers UPI, cards and net banking. So unlike
 * the sandbox provider this one has no VPA to build an intent string from, and
 * `generateQrCode` renders the checkout URL rather than inventing a UPI payload
 * that would point nowhere. See the note on that method.
 */
class PhonePeProvider extends PaymentProvider {
  constructor() {
    super({ id: 'phonepe', label: 'PhonePe', isProduction: phonepe.isProduction });

    /**
     * The OAuth token, held in memory only.
     *
     * Deliberately not persisted. A token is a credential, it lives about as
     * long as a deploy, and writing it to the database would put a bearer
     * credential in a backup for no gain — a restart simply asks for another.
     */
    this.token = null;
    this.tokenExpiresAt = 0;
    this.tokenRequest = null;
  }

  get available() {
    return phonepe.missingConfig().length === 0;
  }

  get unavailableReason() {
    const missing = phonepe.missingConfig();
    if (!missing.length) return null;

    // Names the variables, never the values.
    return `PhonePe is not configured yet. Set ${missing.join(', ')} in the environment.`;
  }

  // ------------------------------------------------------------------ auth

  /**
   * A valid access token, fetched at most once at a time.
   *
   * Two things this guards against. Expiry is checked against PhonePe's own
   * `expires_at` with a margin, so a token that dies mid-flight does not turn
   * into a failed payment. And concurrent callers share one in-flight request:
   * a ride ending at the same moment as three others should ask for one token,
   * not four, and PhonePe rate-limits the token endpoint.
   */
  async accessToken() {
    const now = Math.floor(Date.now() / 1000);
    if (this.token && now < this.tokenExpiresAt - TOKEN_MARGIN_SECONDS) return this.token;

    if (this.tokenRequest) return this.tokenRequest;

    this.tokenRequest = this.fetchToken()
      .then((token) => {
        this.tokenRequest = null;
        return token;
      })
      .catch((err) => {
        this.tokenRequest = null;
        throw err;
      });

    return this.tokenRequest;
  }

  async fetchToken() {
    const body = new URLSearchParams({
      client_id: phonepe.clientId,
      client_version: phonepe.clientVersion,
      client_secret: phonepe.clientSecret,
      grant_type: 'client_credentials'
    });

    const response = await this.request({
      url: `${phonepe.authBaseUrl}/v1/oauth/token`,
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: body.toString(),
      // The token call is the one request that must not echo its own body into
      // an error: the body is the client secret.
      redact: true
    });

    const token = response?.access_token;
    if (!token) throw ApiError.badGateway('PhonePe did not return an access token');

    this.token = token;
    // `expires_at` is epoch seconds. A provider that stopped sending it would
    // otherwise pin the expiry to 1970 and re-authenticate on every call.
    this.tokenExpiresAt = Number(response.expires_at) || now() + 3000;

    logger.info(`[PhonePe] access token issued, expires at ${new Date(this.tokenExpiresAt * 1000).toISOString()}`);
    return token;
  }

  // --------------------------------------------------------------- payments

  /**
   * Opens a checkout for an amount PhonePe will hold us to.
   *
   * `reference` is our own merchant order id and is what every later question
   * about this payment is asked by — the status call takes it, the callback
   * carries it back. It is generated by the payment service, one per attempt,
   * so a retry is a new order rather than a reused one.
   *
   * The amount crosses in paise, as an integer. Rupees would be a rounding bug
   * waiting to happen and PhonePe's own field is a Long of paise.
   */
  async createPayment({ amount, currency, reference, description, redirectUrl, metaInfo }) {
    this.assertUsable();

    if (currency && currency !== 'INR') {
      throw ApiError.badRequest(`PhonePe settles in INR; this ride is priced in ${currency}`);
    }

    const paise = toPaise(amount);
    if (paise < MIN_PAISE) {
      throw ApiError.badRequest(`PhonePe will not take less than ${MIN_PAISE / 100} rupees`);
    }

    const payload = {
      merchantOrderId: reference,
      amount: paise,
      expireAfter: phonepe.expireAfterSeconds,
      paymentFlow: {
        type: 'PG_CHECKOUT',
        message: (description || 'Raahi ride').slice(0, 80),
        merchantUrls: { redirectUrl: redirectUrl || phonepe.redirectUrl }
      }
    };

    if (metaInfo && Object.keys(metaInfo).length) payload.metaInfo = metaInfo;

    const response = await this.signedRequest({
      url: `${phonepe.baseUrl}/checkout/v2/pay`,
      method: 'POST',
      body: payload
    });

    if (!response?.redirectUrl) {
      throw ApiError.badGateway('PhonePe did not return a checkout URL');
    }

    return {
      // Our reference is what we query by, so it is the one we keep as the
      // provider ref. PhonePe's own `orderId` is recorded beside it for
      // support conversations, where they will ask for theirs.
      providerRef: reference,
      providerOrderId: response.orderId || null,
      checkoutRef: response.redirectUrl,
      checkoutUrl: response.redirectUrl,
      expiresAt: response.expireAt ? new Date(Number(response.expireAt)) : null,
      status: mapState(response.state)
    };
  }

  /**
   * What PhonePe says about an order, translated into our own vocabulary.
   *
   * `details=false` asks for the latest attempt rather than every attempt:
   * the question here is "has this been paid", and a customer who failed twice
   * before succeeding produces a longer answer that says the same thing.
   *
   * The amount comes back so the caller can compare it against what was owed.
   * Returning it in rupees rather than paise is deliberate — every other amount
   * in this codebase is rupees, and a paise value escaping into the ledger
   * would be a hundredfold error that looks like a successful payment.
   */
  async verifyPayment(providerRef) {
    this.assertUsable();

    const response = await this.signedRequest({
      url: `${phonepe.baseUrl}/checkout/v2/order/${encodeURIComponent(providerRef)}/status?details=false&errorContext=true`,
      method: 'GET'
    });

    const status = mapState(response?.state);
    const latest = Array.isArray(response?.paymentDetails) ? response.paymentDetails[0] : null;

    return {
      status,
      amount: response?.amount == null ? null : fromPaise(response.amount),
      paidAt: status === PAYMENT_STATUS.PAID ? paidAtOf(latest) : null,
      providerOrderId: response?.orderId || null,
      providerPaymentId: latest?.transactionId || null,
      paymentMode: latest?.paymentMode || null,
      failureReason: status === PAYMENT_STATUS.FAILED ? reasonOf(response, latest) : null,
      raw: safeSummary(response)
    };
  }

  /**
   * A QR for the checkout page, not for a UPI intent.
   *
   * Standard Checkout does not hand out a VPA — the payment instrument is
   * chosen on PhonePe's own page — so there is no NPCI intent string to encode
   * and inventing one would produce a code that scans to nothing, which is the
   * "fake QR" this must not be. What this renders is the real checkout URL, so
   * a customer on a second device can scan it and land on the same PhonePe page
   * the button opens. When the URL is missing, nothing is drawn.
   */
  async generateQrCode({ checkoutUrl }) {
    if (!checkoutUrl) return null;

    return {
      payload: checkoutUrl,
      // Awaited: `qrSvg` is async, and returning the promise would put
      // "[object Promise]" where the markup goes — which renders as nothing
      // and looks like a QR that failed to draw.
      svg: await qrSvg(checkoutUrl),
      format: 'url',
      sandbox: !phonepe.isProduction
    };
  }

  // ---------------------------------------------------------------- refunds

  /**
   * Asks PhonePe to send money back.
   *
   * Returns PENDING in the ordinary case — PhonePe accepts the instruction and
   * settles it asynchronously, so a refund is not complete because this call
   * returned. `refundStatus` is how it is confirmed, and the ledger entry is
   * written then and not before.
   */
  async refund({ merchantRefundId, originalMerchantOrderId, amount }) {
    this.assertUsable();

    const paise = toPaise(amount);
    if (paise < MIN_PAISE) {
      throw ApiError.badRequest(`PhonePe will not refund less than ${MIN_PAISE / 100} rupees`);
    }

    const response = await this.signedRequest({
      url: `${phonepe.baseUrl}/payments/v2/refund`,
      method: 'POST',
      body: { merchantRefundId, originalMerchantOrderId, amount: paise }
    });

    return {
      refundId: response?.refundId || null,
      amount: response?.amount == null ? null : fromPaise(response.amount),
      status: mapState(response?.state)
    };
  }

  async refundStatus(merchantRefundId) {
    this.assertUsable();

    const response = await this.signedRequest({
      url: `${phonepe.baseUrl}/payments/v2/refund/${encodeURIComponent(merchantRefundId)}/status`,
      method: 'GET'
    });

    return {
      status: mapState(response?.state),
      amount: response?.amount == null ? null : fromPaise(response.amount),
      refundId: response?.refundId || null,
      originalMerchantOrderId: response?.originalMerchantOrderId || null,
      failureReason: response?.errorCode || null
    };
  }

  // --------------------------------------------------------------- webhooks

  /**
   * Whether a callback really came from PhonePe.
   *
   * PhonePe hashes the webhook credentials configured in their dashboard as
   * SHA256(username:password) and sends the hex digest as the Authorization
   * header. So this compares a hash we compute from our own copy of those
   * credentials against the one that arrived.
   *
   * Two things worth being explicit about. The comparison is
   * constant-time — a byte-by-byte one leaks the digest to anybody willing to
   * make a few thousand requests. And when the credentials are not configured
   * this returns false rather than true: an unconfigured webhook secret means
   * callbacks cannot be authenticated, which is a reason to refuse them, not a
   * reason to wave them through.
   */
  verifyWebhookSignature(_rawBody, signature) {
    if (!phonepe.webhookConfigured()) {
      logger.warn('[PhonePe] callback rejected: PHONEPE_WEBHOOK_USERNAME/PASSWORD are not set');
      return false;
    }

    if (!signature) return false;

    const expected = crypto
      .createHash('sha256')
      .update(`${phonepe.webhookUsername}:${phonepe.webhookPassword}`)
      .digest('hex');

    // PhonePe sends the bare digest; some integrations put `SHA256 ` in front
    // of it. Both are accepted, nothing else is.
    const presented = String(signature).replace(/^sha256\s+/i, '').trim().toLowerCase();

    const a = Buffer.from(presented, 'utf8');
    const b = Buffer.from(expected, 'utf8');
    if (a.length !== b.length) return false;

    return crypto.timingSafeEqual(a, b);
  }

  /**
   * The merchant order id a callback is about.
   *
   * PhonePe's own guidance is to read the status from the root of `payload` and
   * to route on `event`. This pulls out only the identifier; what the payment
   * is worth and whether it succeeded are re-asked of the status API, because a
   * callback body is something an attacker would love to write.
   */
  // eslint-disable-next-line class-methods-use-this
  parseWebhook(body) {
    const event = body?.event || null;
    const payload = body?.payload || {};

    return {
      event,
      merchantOrderId: payload.merchantOrderId || null,
      providerOrderId: payload.orderId || null,
      merchantRefundId: payload.merchantRefundId || null,
      // Reported for logging and for deciding whether this callback is even
      // about a payment. Never used to settle one.
      reportedState: payload.state || null,
      isRefund: typeof event === 'string' && event.startsWith('pg.refund.')
    };
  }

  // ----------------------------------------------------------------- plumbing

  assertUsable() {
    if (!this.available) throw ApiError.notImplemented(this.unavailableReason);

    if (phonepe.mismatchedEnvironment()) {
      // Loud, because the symptom otherwise is real customers being sent to a
      // sandbox checkout and real rides never being paid for.
      throw ApiError.notImplemented(
        'PhonePe is in sandbox mode on a production deployment. Set PHONEPE_ENV=production or take UPI offline.'
      );
    }
  }

  /** A PhonePe call carrying the bearer token, refreshed once on a 401. */
  async signedRequest(options, { retried = false } = {}) {
    const token = await this.accessToken();

    try {
      return await this.request({
        ...options,
        headers: {
          'Content-Type': 'application/json',
          Authorization: `O-Bearer ${token}`,
          ...(phonepe.merchantId ? { 'X-MERCHANT-ID': phonepe.merchantId } : {}),
          ...options.headers
        },
        body: options.body === undefined ? undefined : JSON.stringify(options.body)
      });
    } catch (err) {
      // A token can expire between the margin check and the call landing, and
      // a single retry with a fresh one turns that into a slow request rather
      // than a failed payment. Only once: a genuine 401 is a bad credential,
      // and retrying it forever is how an account gets locked.
      if (err.upstream === 401 && !retried) {
        this.token = null;
        this.tokenExpiresAt = 0;
        logger.warn('[PhonePe] token rejected; retrying once with a fresh one');
        return this.signedRequest(options, { retried: true });
      }
      throw err;
    }
  }

  /**
   * One HTTP call, with a timeout and without ever leaking a credential.
   *
   * PhonePe's error bodies are returned to us but not to the customer: the
   * caller gets a 502 with a short message, and the detail goes to the log.
   * An upstream gateway's internal error text is not something to render in a
   * payment sheet.
   */
  // eslint-disable-next-line class-methods-use-this
  async request({ url, method, headers, body, redact = false }) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), phonepe.timeoutMs);

    let response;
    try {
      response = await fetch(url, { method, headers, body, signal: controller.signal });
    } catch (err) {
      const cause = err.name === 'AbortError' ? `timed out after ${phonepe.timeoutMs}ms` : err.message;
      logger.error(`[PhonePe] ${method} ${redact ? redactUrl(url) : url} failed: ${cause}`);
      throw ApiError.badGateway('PhonePe could not be reached. Please try again.');
    } finally {
      clearTimeout(timer);
    }

    const text = await response.text();
    let parsed = null;
    try {
      parsed = text ? JSON.parse(text) : null;
    } catch {
      parsed = null;
    }

    if (!response.ok) {
      const detail = parsed?.message || parsed?.code || text?.slice(0, 200) || 'no body';
      logger.error(`[PhonePe] ${method} ${redactUrl(url)} → ${response.status}: ${detail}`);

      const error = ApiError.badGateway(
        response.status === 400 ? 'PhonePe rejected the payment request.' : 'PhonePe could not complete this request.'
      );
      // What PhonePe answered, kept on a field of its own so the retry below
      // can see it. Deliberately NOT written over `status`: that is what the
      // error handler sends to the customer, and a 401 from PhonePe means our
      // token expired, not that the customer needs to sign in again.
      error.upstream = response.status;
      throw error;
    }

    return parsed;
  }
}

/** Refresh this long before PhonePe's own expiry. */
const TOKEN_MARGIN_SECONDS = 60;

/** PhonePe's documented floor, in paise. */
const MIN_PAISE = 100;

const now = () => Math.floor(Date.now() / 1000);

/** Rupees to paise, as an integer. */
const toPaise = (amount) => Math.round(Number(amount) * 100);

/** Paise back to rupees, at two decimal places. */
const fromPaise = (paise) => Math.round(Number(paise)) / 100;

/**
 * PhonePe's order states, mapped to ours.
 *
 * Theirs are PENDING, COMPLETED and FAILED. Anything unrecognised is treated
 * as still pending rather than as failed, because "we do not understand this
 * answer" and "the customer did not pay" are different, and only one of them
 * should close a ride.
 */
function mapState(state) {
  switch (String(state || '').toUpperCase()) {
    case 'COMPLETED':
      return PAYMENT_STATUS.PAID;
    case 'FAILED':
      return PAYMENT_STATUS.FAILED;
    case 'PENDING':
      return PAYMENT_STATUS.PROCESSING;
    default:
      return PAYMENT_STATUS.PROCESSING;
  }
}

/** When the money actually moved, from the attempt PhonePe reports. */
function paidAtOf(detail) {
  const stamp = Number(detail?.timestamp);
  return Number.isFinite(stamp) && stamp > 0 ? new Date(stamp) : new Date();
}

/**
 * Why a payment failed, in words for the customer.
 *
 * PhonePe's error codes are for us, not for them: "AUTHORIZATION_ERROR" on a
 * payment sheet helps nobody. The code goes to the log and the person gets a
 * sentence they can act on.
 */
function reasonOf(response, detail) {
  const code = response?.errorCode || detail?.errorCode || null;
  if (code) logger.warn(`[PhonePe] payment failed with ${code}/${response?.detailedErrorCode || '-'}`);

  return 'The payment did not go through at PhonePe.';
}

/** The parts of a response worth keeping on the payment record. No instruments. */
function safeSummary(response) {
  if (!response) return null;

  const latest = Array.isArray(response.paymentDetails) ? response.paymentDetails[0] : null;

  return {
    orderId: response.orderId || null,
    state: response.state || null,
    // Masked card numbers and VPAs are the customer's, and storing them buys
    // nothing a support conversation needs — the transaction id identifies the
    // payment to PhonePe on its own.
    paymentMode: latest?.paymentMode || null,
    transactionId: latest?.transactionId || null,
    errorCode: response.errorCode || null
  };
}

/** A URL with any query string dropped, for logs. */
const redactUrl = (url) => String(url).split('?')[0];

module.exports = { PhonePeProvider, mapState, toPaise, fromPaise };
